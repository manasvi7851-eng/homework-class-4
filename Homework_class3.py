
import seaborn as sns
import matplotlib.pyplot as plt
planets = sns.load_dataset("planets")
print(planets.head())
print(planets.info())
print(planets.describe())
planets = planets.dropna()
sns.histplot(data=planets, x="year")
plt.title("Planet Discoveries by Year")
plt.show()
sns.countplot(data=planets, y="method")
plt.title("Discovery Methods")
plt.show()
sns.histplot(data=planets, x="orbital_period")
plt.title("Orbital Periods")
plt.show()
sns.histplot(data=planets, x="mass")
plt.title("Planet Masses")
plt.show()
sns.scatterplot(data=planets, x="mass", y="orbital_period")
plt.title("Mass vs Orbital Period")
plt.show()
sns.heatmap(planets.select_dtypes("number").corr(), annot=True)
plt.title("Correlation Heatmap")
plt.show()
print("Total planets:", len(planets))
print("Discovery methods:", planets["method"].nunique())
print("Average planet mass:", planets["mass"].mean())
print("Average orbital period:", planets["orbital_period"].mean())